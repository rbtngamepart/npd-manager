// 튜토리얼 단원과 단계
// target  : 화면에서 강조할 요소의 data-tour 값 (없으면 화면 가운데 설명 카드)
// route   : 이 단계를 보여줄 화면. "project" = 프로젝트 상세 화면
// ready   : 이벤트를 보내기 전에 화면에 나타나야 하는 요소
// event   : 화면에 보내는 동작 (탭 전환, 단계 패널 열기 등)
// role    : 이 권한이 있을 때만 보여줌

export type TourRoute = "/" | "/projects/new" | "/templates" | "/admin" | "/departments" | "/calendar" | "/atlassian" | "project";
export type Role = "editor" | "gamepart" | "admin";

export type TourEvent =
  | { type: "tab"; tab: "gantt" | "pm" | "logs" | "settings" }
  | { type: "open-stage" }
  | { type: "close-stage" }
  | { type: "import"; open: boolean };

export interface TourStep {
  target?: string;
  title: string;
  body: string;
  route?: TourRoute;
  ready?: string;
  event?: TourEvent;
  role?: Role;
}

export interface Chapter {
  id: string;
  title: string;
  desc: string;
  minutes: number;
  needsProject?: boolean;
  role?: Role;
  steps: TourStep[];
  /** 단원이 끝날 때 화면 정리 */
  cleanup?: TourEvent[];
}

